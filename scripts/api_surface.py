#!/usr/bin/env python3
"""Snapshot each port's public API, so a change to it is a decision rather than an accident.

    python3 scripts/api_surface.py                  # rewrite docs/api-surface/<port>.txt for every port
    python3 scripts/api_surface.py python go        # just these ports
    python3 scripts/api_surface.py --check [ports]  # exit 1 and print a diff if a snapshot is stale

Each snapshot comes from the real build, not the source text:

  python      imports the three packages (client_attestation_sdk, .token_validator, .authz_challenge) and
              lists every name in their __all__ with its parameters and defaults (no annotations: their
              repr changes between Python versions). Needs the package's dependencies importable; it
              runs with this interpreter, or --python PATH, and PYTHONPATH=python/src.
  typescript  emits declarations for the two package entry points ("." and "./validator") with tsc and
              follows their re-exports to each declaration, without comments or private members.
              It also type-checks those declarations on their own, so nothing public can refer to a
              stripped @internal name. Needs `npm ci` in typescript/.
  go          `go doc -all` of the module root and tokenvalidator, declarations only (doc text and
              comments dropped).
  java        `javap -public` over every class in the exported packages (not ...internal), members
              sorted. Compiles first with ./mvnw unless --no-build is given.

The SDK version is replaced by <VERSION> so a release doesn't churn the snapshots. CI runs --check in each
port's job; an intended API change regenerates the snapshot in the same pull request (see CONTRIBUTING.md).
"""
import argparse
import difflib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "api-surface")
PORTS = ("python", "typescript", "go", "java")
VERSION = open(os.path.join(ROOT, "VERSION"), encoding="utf-8").read().strip()
HEADER = "# Generated by scripts/api_surface.py from the {port} build. Do not edit; regenerate.\n"


def run(cmd, cwd, env=None):
    proc = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout + proc.stderr)
        sys.exit(f"api_surface: {' '.join(cmd)} failed in {os.path.relpath(cwd, ROOT)}")
    return proc.stdout


# --- Python -------------------------------------------------------------------------------------------

PY_INTROSPECT = r'''
import importlib, inspect, re, sys

PACKAGES = ["client_attestation_sdk", "client_attestation_sdk.token_validator",
            "client_attestation_sdk.authz_challenge"]
OURS = "client_attestation_sdk"

def value(v):
    if isinstance(v, (str, int, float, bool, type(None), tuple, frozenset)):
        return repr(v)
    if inspect.isfunction(v) or inspect.isclass(v):
        return v.__qualname__
    return re.sub(r" at 0x[0-9a-f]+", "", repr(v))

def params(fn, drop_self=False):
    try:
        sig = inspect.signature(fn)
    except (TypeError, ValueError):
        return "(...)"
    out, star = [], False
    ps = list(sig.parameters.values())
    if drop_self and ps and ps[0].name in ("self", "cls"):
        ps = ps[1:]
    for i, p in enumerate(ps):
        if p.kind is p.KEYWORD_ONLY and not star:
            out.append("*")
            star = True
        if p.kind is p.VAR_POSITIONAL:
            star = True
            out.append("*" + p.name)
        elif p.kind is p.VAR_KEYWORD:
            out.append("**" + p.name)
        else:
            out.append(p.name + ("" if p.default is p.empty else "=" + value(p.default)))
        if p.kind is p.POSITIONAL_ONLY and (i + 1 == len(ps) or ps[i + 1].kind is not p.POSITIONAL_ONLY):
            out.append("/")
    return "(" + ", ".join(out) + ")"

def members(cls):
    lines = []
    seen = set()
    for klass in cls.__mro__:
        if not klass.__module__.startswith(OURS):
            continue
        for name, attr in vars(klass).items():
            if name in seen or (name.startswith("_") and name != "__init__"):
                continue
            seen.add(name)
            if name in getattr(cls, "__dataclass_fields__", {}):
                continue                       # listed once, in the dataclass fields line
            if name == "__init__":
                if inspect.isfunction(attr) and not getattr(cls, "_is_protocol", False):
                    lines.append("  __init__" + params(attr, drop_self=True))
            elif isinstance(attr, property):
                lines.append("  property " + name + (" (settable)" if attr.fset else ""))
            elif isinstance(attr, classmethod):
                lines.append("  classmethod " + name + params(attr.__func__, drop_self=True))
            elif isinstance(attr, staticmethod):
                lines.append("  staticmethod " + name + params(attr.__func__))
            elif inspect.isfunction(attr):
                lines.append("  def " + name + params(attr, drop_self=True))
            elif inspect.isclass(attr):
                lines.append("  class " + name)
            else:
                lines.append("  " + name + " = " + value(attr))
    fields = getattr(cls, "__dataclass_fields__", None)
    if fields:
        lines.append("  dataclass fields: " + ", ".join(fields))
    return sorted(lines)

for pkg in PACKAGES:
    mod = importlib.import_module(pkg)
    print("== " + pkg)
    for name in sorted(mod.__all__):
        obj = getattr(mod, name)
        if inspect.ismodule(obj):
            print("module " + name)
            for n in sorted(k for k in vars(obj) if not k.startswith("_")):
                v = getattr(obj, n)
                if not inspect.ismodule(v):
                    print("  " + n + " = " + value(v))
        elif inspect.isclass(obj):
            bases = [b.__name__ for b in obj.__bases__ if b is not object]
            print("class " + name + ("(" + ", ".join(bases) + ")" if bases else ""))
            for line in members(obj):
                print(line)
        elif callable(obj):
            print("def " + name + params(obj))
        else:
            print(name + " = " + value(obj))
'''


def python_surface(args):
    env = dict(os.environ, PYTHONPATH=os.path.join(ROOT, "python", "src"), PYTHONDONTWRITEBYTECODE="1")
    return run([args.python, "-c", PY_INTROSPECT], cwd=os.path.join(ROOT, "python"), env=env)


# --- TypeScript ---------------------------------------------------------------------------------------

def strip_comments(text):
    # a deprecation is part of the API, so it survives as a marker; any other comment goes
    text = re.sub(r"/\*\*(?:(?!\*/).)*@deprecated.*?\*/\s*", "@deprecated ", text, flags=re.S)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    return re.sub(r"(?m)^\s*//.*$", "", text)


def ts_declarations(path):
    """Top-level declarations of a .d.ts file, by exported name, and its re-export statements."""
    text = strip_comments(open(path, encoding="utf-8").read())
    chunks, current = [], []
    for line in text.splitlines():
        if not line.strip():
            continue
        if line[0] not in " \t})]" and current:
            chunks.append("\n".join(current))
            current = []
        current.append(line)
    if current:
        chunks.append("\n".join(current))
    decls, reexports = {}, []
    for chunk in chunks:
        if chunk.startswith("import ") or chunk.startswith("export {};"):
            continue
        if re.match(r"export (type )?\{", chunk) or chunk.startswith("export * "):
            reexports.append(" ".join(chunk.split()))
            continue
        m = re.match(r"(?:@deprecated )?(?:export )?(?:declare )?(?:abstract )?(class|interface|type|const|function|enum|namespace) "
                     r"([A-Za-z_$][\w$]*)", chunk)
        if not m:
            raise SystemExit(f"api_surface: can't read this declaration in {path}:\n{chunk}")
        body = "\n".join(l for l in chunk.splitlines()
                         if not re.match(r"\s+(private |#private)", l))
        decls.setdefault(m.group(2), []).append(body)
    return decls, reexports


def ts_exports(dts_dir, rel, seen=None):
    """name -> declaration text, for everything a module exports (following re-exports)."""
    path = os.path.join(dts_dir, rel)
    decls, reexports = ts_declarations(path)
    out = {name: "\n".join(body) for name, body in decls.items()
           if any(re.match(r"(@deprecated )?export ", b) for b in body)}
    base = os.path.dirname(rel)
    for stmt in reexports:
        m = re.match(r'export \* as (\w+) from "(.+?)";', stmt)
        if m:
            target = os.path.normpath(os.path.join(base, m.group(2).replace(".js", ".d.ts")))
            inner = ts_exports(dts_dir, target)
            out[m.group(1)] = "namespace " + m.group(1) + " {\n" + "\n".join(
                "  " + inner[k].replace("\n", "\n  ") for k in sorted(inner)) + "\n}"
            continue
        m = re.match(r'export (?:type )?\{(.*)\}(?: from "(.+?)")?;', stmt)
        if not m:
            raise SystemExit(f"api_surface: can't read this export in {path}: {stmt}")
        if m.group(2):
            target = os.path.normpath(os.path.join(base, m.group(2).replace(".js", ".d.ts")))
            source = ts_exports(dts_dir, target)
        else:
            local, _ = ts_declarations(path)
            source = {k: "\n".join(v) for k, v in local.items()}
        for item in m.group(1).split(","):
            item = item.strip()
            if not item:
                continue
            item = re.sub(r"^type ", "", item)
            orig, _, alias = item.partition(" as ")
            alias = alias or orig
            if orig not in source:
                raise SystemExit(f"api_surface: {rel} re-exports {orig}, which isn't declared")
            decl = source[orig]
            out[alias] = decl if alias == orig else f"{alias} = {decl}"
    return out


def typescript_surface(args):
    ts = os.path.join(ROOT, "typescript")
    tsc = os.path.join(ts, "node_modules", ".bin", "tsc")
    if not os.path.exists(tsc):
        sys.exit("api_surface: run `npm ci` in typescript/ first")
    pkg = json.load(open(os.path.join(ts, "package.json"), encoding="utf-8"))
    tmp = tempfile.mkdtemp(prefix=".api-surface-", dir=ts)   # inside the package, so `jose` resolves
    try:
        run([tsc, "-p", "tsconfig.json", "--declaration", "--emitDeclarationOnly", "--outDir", tmp], cwd=ts)
        # The declarations a consumer gets must type-check on their own: nothing they mention may have
        # been stripped as @internal.
        entries = [os.path.join(tmp, os.path.relpath(os.path.join(ts, spec["types"]), os.path.join(ts, "dist")))
                   for spec in pkg["exports"].values()]
        run([tsc, "--ignoreConfig", "--noEmit", "--strict", "--skipLibCheck", "false", "--module", "nodenext",
             "--moduleResolution", "nodenext", "--target", "es2022", "--types", "node"] + entries, cwd=ts)
        lines = []
        for entry, spec in sorted(pkg["exports"].items()):
            types = spec["types"]
            rel = os.path.relpath(os.path.join(ts, types), os.path.join(ts, "dist"))
            lines.append(f'== "{pkg["name"]}{entry[1:]}" ({types})')
            exports = ts_exports(tmp, rel)
            for name in sorted(exports):
                text = re.sub(r"export |declare ", "", exports[name])
                lines.append(text.rstrip())
            lines.append("")
        lines.append("== package.json exports")
        lines.append(json.dumps(pkg["exports"], indent=2, sort_keys=True))
        return "\n".join(lines) + "\n"
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


# --- Go -----------------------------------------------------------------------------------------------

def go_declarations(text):
    out, depth, started = [], 0, False
    for line in text.splitlines():
        if line in ("CONSTANTS", "VARIABLES", "FUNCTIONS", "TYPES"):
            started = True                     # everything before the first heading is the package doc
            continue
        if line.startswith("package "):
            out.append(line.split(" //")[0])
            continue
        if not started:
            continue
        if depth == 0:
            if line.strip().startswith("Deprecated:") and out:
                out[-1] += "  // Deprecated"   # a deprecation is part of the API; other doc text isn't
                continue
            if not line or line[0] in " \t":
                continue                       # declaration docs are indented
            line = re.sub(r"\s+// .*$", "", line)
            out.append(line)
            if line.endswith("{") or line.endswith("("):
                depth = 1
            continue
        stripped = line.strip()
        if stripped.startswith("//") or not stripped:
            continue
        line = re.sub(r"\s+// .*$", "", line)
        out.append(line)
        depth += line.count("{") + line.count("(") - line.count("}") - line.count(")")
        if line[0] not in " \t" and line.rstrip() in ("}", ")"):
            depth = 0
    return out


def go_surface(args):
    go = os.path.join(ROOT, "go")
    lines = []
    for pkg in (".", "./tokenvalidator"):
        lines.append(f"== {pkg}")
        lines.extend(go_declarations(run(["go", "doc", "-all", pkg], cwd=go)))
        lines.append("")
    return "\n".join(lines) + "\n"


# --- Java ---------------------------------------------------------------------------------------------

def java_surface(args):
    java = os.path.join(ROOT, "java")
    if not args.no_build:
        run(["./mvnw", "-B", "-q", "-DskipTests", "compile"], cwd=java)
    classes = os.path.join(java, "target", "classes")
    names = []
    for dirpath, _, files in os.walk(classes):
        rel = os.path.relpath(dirpath, classes)
        if rel.split(os.sep)[-1] == "internal" or rel == ".":
            continue                           # the module doesn't export internal
        for f in files:
            if f.endswith(".class") and f != "package-info.class":
                names.append(os.path.join(rel, f[:-6]).replace(os.sep, "."))
    module = os.path.join(classes, "module-info.class")
    out = run(["javap", "-public", "-cp", classes] + sorted(names) + ([module] if os.path.exists(module) else []),
              cwd=java)
    out = out.replace("global.idpartners.clientattestation.", "").replace("java.lang.", "")
    blocks, current = [], None
    for line in out.splitlines():
        if line.startswith("Compiled from"):
            continue
        if not line.startswith(" ") and line.rstrip().endswith("{"):
            # javap prints a non-public class it was asked about; only public ones are API
            current = [line.rstrip(), []] if re.match(r"(public |module )", line) else [None, []]
        elif line.strip() == "}" and current is not None:
            if current[0] is not None:
                blocks.append(current)
            current = None
        elif current is not None and line.strip():
            current[1].append("  " + line.strip())
    lines = ["# names are relative to global.idpartners.clientattestation; java.lang. is dropped"]
    for head, body in sorted(blocks, key=lambda b: re.sub(r".*(class|interface|enum|module) ", "", b[0])):
        lines.append(head)
        lines.extend(sorted(body))
        lines.append("}")
    return "\n".join(lines) + "\n"


SURFACES = {"python": python_surface, "typescript": typescript_surface, "go": go_surface, "java": java_surface}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("ports", nargs="*", help="any of python, typescript, go, java (default: all four)")
    parser.add_argument("--check", action="store_true", help="fail with a diff if a snapshot is stale")
    parser.add_argument("--python", default=sys.executable, help="interpreter for the Python port")
    parser.add_argument("--no-build", action="store_true", help="Java: use target/classes as it is")
    args = parser.parse_args()
    unknown = [p for p in args.ports if p not in PORTS]
    if unknown:
        parser.error(f"unknown port(s) {unknown}; choose from {', '.join(PORTS)}")
    stale = False
    for port in args.ports or PORTS:
        text = HEADER.format(port=port) + SURFACES[port](args).replace(VERSION, "<VERSION>")
        path = os.path.join(OUT, port + ".txt")
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if args.check:
            if old != text:
                stale = True
                rel = os.path.relpath(path, ROOT)
                sys.stdout.writelines(difflib.unified_diff(
                    old.splitlines(True), text.splitlines(True), rel + " (committed)", rel + " (this build)"))
                print(f"\n{rel} is stale. If this API change is intended, run "
                      f"`python3 scripts/api_surface.py {port}`, commit the result and add a CHANGELOG line.")
            else:
                print(f"{port}: API surface matches docs/api-surface/{port}.txt")
        else:
            os.makedirs(OUT, exist_ok=True)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
            print(f"{port}: wrote docs/api-surface/{port}.txt")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
